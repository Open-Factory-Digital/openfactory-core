def test_the_rule_and_its_reason(rel, body, kind, why):
    """First match wins, and `kind_reason` names the rule — the inventory's one failure mode
    (a wrong kind) is visible where it was decided. Through `classify` directly: the walk prunes
    `node_modules/` and `.vscode/` before a rule ever sees them, and the rule must still be right
    for the checkout that does not prune (a bundle read back, a path cited by a concept)."""
    got_kind, reason = classify(rel, text=body if isinstance(body, str) else None)
    assert got_kind == kind, (got_kind, reason)
    assert why in reason, reason


def test_every_file_is_a_row_and_the_kinds_sum_to_the_total(tmp_path):
    files = {"a.py": "x = 1", "b/c.md": "# c", "d.xyz": "?", "e/f.yaml": "k: v",
             "tests/test_a.py": "def test(): pass"}
    taken = take_inventory(_repo(tmp_path, files))
    assert sorted(r.path for r in taken.files) == sorted(files)
    assert sum(taken.by_kind.values()) == len(files)
    assert all(r.kind_reason for r in taken.files), "a row with no reason is a guess"


def test_a_file_no_rule_places_is_counted_not_dropped(tmp_path):
    taken = take_inventory(_repo(tmp_path, {"a.py": "x = 1", "thing.xyz": "?", "other.qqq": "!"}))
    assert taken.unclassified == ["other.qqq", "thing.xyz"]
    assert taken.by_kind["unclassified"] == 2
    kinds = [g.kind for g in inventory_gaps(taken)]
    assert kinds.count("unclassified") == 2, "each unclassified file is its own gap"


def test_dead_code_needs_a_floor(tmp_path):
    """Three comment lines are a header, not a dead file."""
    taken = take_inventory(_repo(tmp_path, {"a.cs": "// a\n// b\n// c\n"}))
    assert taken.files[0].kind == "code"


def test_the_pilots_finding_a_fully_commented_file_is_dead_code_and_a_gap(tmp_path):
    """Fifteen `Functions/**/*.cs` that were 100 % commented out — a convention glob counted
    them as functions. Content shape says otherwise, whatever the folder is called."""
    taken = take_inventory(_repo(tmp_path, {"Functions/Handler.cs": DEAD}))
    assert taken.files[0].kind == "dead-code"
    gap = next(g for g in inventory_gaps(taken) if g.kind == "dead-code")
    assert gap.path == "Functions/Handler.cs" and "6 of 6" in gap.detail


def test_the_fingerprint_is_the_checkers_own(tmp_path):
    body = "def charge():\n    return 1\n"
    taken = take_inventory(_repo(tmp_path, {"rules.py": body}))
    assert taken.files[0].fingerprint == _bundle._sha256(body.encode("utf-8"))


def test_lines_are_counted_with_or_without_a_final_newline(tmp_path):
    taken = take_inventory(_repo(tmp_path, {"a.py": "1\n2\n3\n", "b.py": "1\n2\n3"}))
    assert {r.path: r.lines for r in taken.files} == {"a.py": 3, "b.py": 3}


def test_an_unreadable_directory_is_declared_not_skipped(tmp_path, monkeypatch):
    """`os.walk` swallows a directory it cannot open — the survey's C-49 collapse. The inventory
    carries the survey's own declaration, and it becomes a gap."""
    from openfactory.onboarding import context

    real = context._collect_files

    def blind(repo, max_files):
        files = real(repo, max_files)
        return files.model_copy(update={"unreadable": ["vendor/blob"], "truncated": True})

    monkeypatch.setattr(context, "_collect_files", blind)
    taken = take_inventory(_repo(tmp_path, {"a.py": "x = 1"}))
    assert taken.unreadable == ["vendor/blob"] and taken.truncated
    kinds = {g.kind: g for g in inventory_gaps(taken)}
    assert kinds["unreadable"].path == "vendor/blob" and "not as empty" in kinds["unreadable"].detail
    assert "truncated" in kinds and "not inventoried" in kinds["truncated"].detail


def test_a_file_that_cannot_be_read_is_an_error_row(tmp_path, monkeypatch):
    real = inv._read

    def half_blind(path):
        return (None, None) if path.name == "b.py" else real(path)

    monkeypatch.setattr(inv, "_read", half_blind)
    taken = take_inventory(_repo(tmp_path, {"a.py": "x = 1", "b.py": "y = 2"}))
    assert taken.errors == ["b.py"]
    row = next(r for r in taken.files if r.path == "b.py")
    assert row.kind == "code" and row.kind_reason.endswith("(could not be read)")
    assert any(g.kind == "unreadable" and g.path == "b.py" for g in inventory_gaps(taken))


