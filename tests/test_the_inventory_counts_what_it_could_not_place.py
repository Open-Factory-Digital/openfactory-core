"""The inventory: every file, its kind, and why — and the remainder COUNTED (OKF §6.1).

A bundle's coverage table divided by the module map: "5 of 412 modules described" — and a module
row cannot say which FILES were never asked about. The reference format's pilot found what that
hides: a convention glob returned fifteen files that were 100 % commented out and missed the
sixty-four live entry points beside them, and a bundle with four concepts over eighty-two files
exited clean because every kind had a reason. So the inventory is exhaustive by construction — a
file no rule places is `unclassified` and a row, a directory the walk could not open is named, a
walk that hit its ceiling says so — and the coverage table gains one row per kind, with the
exemption stated and the rows nothing excuses marked `excused: False`.

Measured on the core's own tree before any of this: 866 files, and the first cut of the rules
placed `.git` (a worktree's pointer FILE), `registry.yaml.example` and three `*.Dockerfile`s in
`unclassified`, called thirty-six `__init__.py` entry points, and reported a hundred credential
risks — `token_env: "SLACK_BOT_TOKEN"` and `token_pool.ssm` among them. The rules below are the
ones that survived that measurement; the guards pin each of those cuts.
"""
