# --- coverage --------------------------------------------------------------------------------

def _concept(*paths: str) -> Concept:
    return Concept(type="policy", title="t", description="d", what_it_does="w",
                   sources=[ConceptSource(repo="r", path=p, commit="c", fingerprint="f",
                                          lines="1-2") for p in paths])


def _taken(tmp_path: Path) -> Inventory:
    return take_inventory(_repo(tmp_path, {
        "src/a.py": "x = 1", "src/b.py": "y = 2", "tests/test_a.py": "def test(): pass",
        "app.yaml": "k: v", "odd.xyz": "?"}))


def test_one_row_per_kind_with_the_exemption_or_the_debt(tmp_path):
    rows = {r.kind: r for r in coverage_by_kind(_taken(tmp_path), [_concept("src/a.py")])}
    assert set(rows) == {"code", "test", "configuration", "unclassified"}
    assert (rows["code"].inventoried, rows["code"].concepts, rows["code"].reason) == (2, 1, "")
    assert rows["test"].concepts == 0 and rows["test"].excused is True
    assert rows["test"].reason == WHY_NOT["test"][0]
    assert rows["unclassified"].reason == NO_EXEMPTION and rows["unclassified"].excused is False


def test_code_the_budget_did_not_reach_is_explained_but_not_excused(tmp_path):
    rows = {r.kind: r for r in coverage_by_kind(_taken(tmp_path), [])}
    assert rows["code"].reason == BUDGET_DID_NOT_REACH and rows["code"].excused is False


def test_concepts_are_counted_per_concept_not_per_file(tmp_path):
    rows = {r.kind: r for r in coverage_by_kind(_taken(tmp_path), [_concept("src/a.py",
                                                                             "src/b.py")])}
    assert rows["code"].concepts == 1


def test_the_backfills_coverage_gains_the_kind_rows(tmp_path):
    from openfactory.onboarding.onboard import _coverage
    from tests.test_a_concept_is_earned_not_declared import _survey

