def test_the_backfill_writes_the_inventory_beside_the_concepts(tmp_path):
    """End to end through `_write_concepts`: the inventory is taken before the agent pass, its
    gaps join the manifest's, its rows join the coverage table, and both files land in the
    bundle beside `index.md`."""
    from types import SimpleNamespace

    import yaml

    from openfactory.knowledge.okf import OKF_MANIFEST_FILE
    from openfactory.knowledge.pipeline import okf_subpath
    from openfactory.onboarding.onboard import _write_concepts
    from tests.test_a_concept_is_earned_not_declared import _answer, _survey
    from tests.test_a_concept_is_earned_not_declared import _repo as _git_repo

    (tmp_path / "src").mkdir()
    repo = _git_repo(tmp_path / "src")
    (repo / "odd.xyz").write_text("?", encoding="utf-8")
    docs = tmp_path / "docs"
    docs.mkdir()
    project = SimpleNamespace(name="demo", forge=SimpleNamespace(repo="acme/api", kind="github"),
                              tracker=None)
    written = _write_concepts(project, _survey(repo), repo, docs,
                              ask_fn=lambda _p: _answer(), commit="deadbee")
    bundle = docs / okf_subpath("acme/api")
    assert (bundle / INVENTORY_FILE).is_file() and (bundle / INVENTORY_SUMMARY_FILE).is_file()
    assert any(w.endswith(INVENTORY_FILE) for w in written)
    manifest = yaml.safe_load((bundle / OKF_MANIFEST_FILE).read_text(encoding="utf-8"))
    kinds = {row["kind"]: row for row in manifest["coverage"]}
    assert kinds["code"]["inventoried"] == 1 and kinds["code"]["concepts"] == 1, kinds
    assert kinds["unclassified"]["excused"] is False
    assert any(g["kind"] == "unclassified" and g["path"] == "odd.xyz" for g in manifest["gaps"])
    assert "| unclassified | 1 | 0 |" in (bundle / "index.md").read_text(encoding="utf-8")


def test_the_cli_takes_an_inventory_without_a_project(tmp_path):
    from typer.testing import CliRunner

    from openfactory.cli import app

    repo = _repo(tmp_path / "r", {"a.py": "x = 1", "odd.xyz": "?"})
    out = CliRunner().invoke(app, ["knowledge", "inventory", str(repo), "--out",
                                  str(tmp_path / "b")])
    assert out.exit_code == 0, out.output
    assert "files: 2" in out.output and "unclassified: odd.xyz" in out.output
    assert (tmp_path / "b" / INVENTORY_FILE).is_file()
    missing = CliRunner().invoke(app, ["knowledge", "inventory", str(tmp_path / "nope")])
    assert missing.exit_code == 2, missing.output


def test_the_walk_is_the_surveys_own():
    """One walk, not two: the inventory reuses `_collect_files` rather than owning a second
    pruning rule set the module map would drift away from."""
    src = (ROOT / "openfactory/knowledge/inventory.py").read_text(encoding="utf-8")
